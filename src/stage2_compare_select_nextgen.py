"""
Next-generation Stage-2 comparison with validation AUC-primary selection.

Task:
    bacterial pneumonia (negative=0) vs viral pneumonia (positive=1)

This script DOES NOT train new models. It audits and compares the saved
validation/test prediction files generated by the existing Stage-2 training
scripts. It calculates 2,000 filename-group bootstrap confidence intervals for
all main metrics, chooses an operational Stage-2 model using validation data
only, and exports a unified selected-model prediction file.

Recommended location:
    <project-root>\\src\\stage2_compare_select_nextgen.py

Run:
    python -m src.stage2_compare_select_nextgen ^
        --project-root "<project-root>" ^
        --reps 2000

Important:
1. Positive class = viral pneumonia.
2. Negative class = bacterial pneumonia.
3. The fixed exploratory test data are never used for model or threshold selection.
4. Models whose scores depend on ranking the entire test cohort are excluded
   from operational selection by default.
5. The group-OOF fixed stack is reported as a benchmark, but is not mixed into
   the ordinary held-out-validation ranking by default.
"""

